    private void modificarNotaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_modificarNotaActionPerformed
        // TODO add your handling code here:
        try {
            if (curso == null) {
                jTextArea1.setText("Primero debes crear el curso.");
                return;
            }

            int cod = Integer.parseInt(codigoBuscar.getText());
            double nuevaNot = Double.parseDouble(nuevaNota.getText());

            Estudiante estudiante = curso.buscarEstudiante(cod);

            if (estudiante == null) {
                jTextArea1.setText("Estudiante no encontrado.");
                return;
            }

            String opcion = comboMateria.getSelectedItem().toString();

            if (opcion.equals("Hardware")) {
                Desarrollo desa = (Desarrollo) estudiante.getDesarrollo();
                desa.modificarNota(1, nuevaNot);

            } else if (opcion.equals("Software")) {
                Desarrollo desa = (Desarrollo) estudiante.getDesarrollo();
                desa.modificarNota(2, nuevaNot);

            } else if (opcion.equals("Matemáticas")) {
                estudiante.getMatematicas().setNota(nuevaNot);
            }

            jTextArea1.setText("Nota modificada correctamente.\n\n");

        } catch (Exception e) {
            jTextArea1.setText("Error: " + e.getMessage());
        }
        
    }//GEN-LAST:event_modificarNotaActionPerformed

