    private void agregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_agregarActionPerformed

        try {

            if (curso == null) {
                jTextArea1.setText("Primero debes crear el curso.");
                return;
            }

            String nom = nombre.getText();
            int cod = Integer.parseInt(codigo.getText());

            double notaMate = Double.parseDouble(notaMatematicas.getText());
            double notaSoft = Double.parseDouble(notaSoftware.getText());
            double notaHard = Double.parseDouble(notaHardware.getText());

            Materia matematicas = new Matematicas(notaMate);
            Materia desarrollo = new Desarrollo(notaSoft, notaHard);

            Estudiante estudiante = new Estudiante(nom, cod, matematicas, desarrollo);

            String mensaje = curso.agregarEstudiante(estudiante);

            jTextArea1.setText(mensaje);

        } catch (Exception e) {
            jTextArea1.setText("Error: " + e.getMessage());
        }
    }//GEN-LAST:event_agregarActionPerformed

